"""
mongo_label_export.py
======================

Fetches documents from every MongoDB collection used by the "smriti-kunj"
backend, attaches the human-readable labels (title / description / unit /
domain) defined in SCHEMA_LABELLING_GUIDE.md, and writes everything to a
single "long format" CSV:

    collection | document_id | field_name | title | description | unit |
    domain | value | is_labelled

One row = one (document, field) pair. This format lets you open the CSV in
Excel/Sheets, filter by collection or domain, and see the raw value next to
its plain-English meaning -- instead of guessing what `avg_latency_ms` or
`r_squared` means from a bare export.

Fields that are NOT yet described in the guide are still exported (so no
data is silently dropped) but are flagged with is_labelled=False and a
generic humanized title, so you can spot gaps at a glance.

Usage
-----
    pip install pymongo

    # Option 1: environment variables
    export MONGO_URI="mongodb://localhost:27017"
    export MONGO_DB="cognitive_assist"
    python mongo_label_export.py

    # Option 2: command-line flags (override env vars)
    python mongo_label_export.py --uri "mongodb+srv://user:pass@cluster/" \
                                  --db cognitive_assist \
                                  --out labelled_export.csv \
                                  --collections game_sessions drift_metrics

No code in the actual backend repo is touched -- this is a standalone,
read-only export tool.
"""

