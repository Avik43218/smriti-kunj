DEFAULT_COLLECTIONS = [
    "users",
    "device_pairing_tokens",
    "otp_codes",
    "revoked_tokens",
    "game_sessions",
    "voice_interactions",
    "drift_metrics",
    "alerts",
    "bandit_arm_state",
    "family_members",
    "patient_reminders",
]

CSV_COLUMNS = [
    "collection",
    "document_id",
    "field_name",
    "title",
    "description",
    "unit",
    "domain",
    "value",
    "is_labelled",
]


def export_to_csv(
    uri: str,
    db_name: str,
    collections: Iterable[str],
    out_path: str,
    limit: Optional[int] = None,
) -> Dict[str, int]:
    client = MongoClient(uri, serverSelectionTimeoutMS=8000)
    db = client[db_name]

    stats: Dict[str, int] = {}

    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS)
        writer.writeheader()

        for coll_name in collections:
            if coll_name not in db.list_collection_names():
                print(f"[skip] '{coll_name}' does not exist in database '{db_name}'")
                stats[coll_name] = 0
                continue

            cursor = db[coll_name].find({}, limit=limit) if limit else db[coll_name].find({})
            row_count = 0

            for doc in cursor:
                doc = flatten_document(doc)
                document_id = serialize_value(doc.get("_id", ""))

                for field_name, value in doc.items():
                    label = get_label(coll_name, field_name)
                    writer.writerow({
                        "collection": coll_name,
                        "document_id": document_id,
                        "field_name": field_name,
                        "title": label["title"],
                        "description": label["description"],
                        "unit": label["unit"],
                        "domain": label["domain"],
                        "value": serialize_value(value),
                        "is_labelled": label["is_labelled"],
                    })
                    row_count += 1

            stats[coll_name] = row_count
            print(f"[ok] {coll_name}: exported {row_count} labelled field-rows")

    client.close()
    return stats


