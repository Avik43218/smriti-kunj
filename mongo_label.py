# 4. CLI
# --------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Fetch MongoDB data, attach schema-guide labels, export to CSV."
    )
    parser.add_argument(
        "--uri",
        default=os.environ.get("MONGO_URI", "mongodb://localhost:27017"),
        help="MongoDB connection URI (default: $MONGO_URI or mongodb://localhost:27017)",
    )
    parser.add_argument(
        "--db",
        default=os.environ.get("MONGO_DB", "cognitive_assist"),
        help="Database name (default: $MONGO_DB or 'cognitive_assist')",
    )
    parser.add_argument(
        "--collections",
        nargs="*",
        default=DEFAULT_COLLECTIONS,
        help="Specific collections to export (default: all known collections)",
    )
    parser.add_argument(
        "--out",
        default="labelled_export.csv",
        help="Output CSV file path (default: labelled_export.csv)",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Optional max number of documents per collection (useful for a quick sample run)",
    )
    args = parser.parse_args()

    print(f"Connecting to {args.db} @ {args.uri} ...")
    stats = export_to_csv(args.uri, args.db, args.collections, args.out, args.limit)

    total_rows = sum(stats.values())
    print("\nSummary:")
    for coll, count in stats.items():
        print(f"  {coll:<22} {count} field-rows")
    print(f"\nWrote {total_rows} total rows to {args.out}")


if __name__ == "__main__":
    main()
    