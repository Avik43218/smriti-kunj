# 2. Helpers
# --------------------------------------------------------------------------

def humanize(field_name: str) -> str:
    """Fallback title generator for fields not yet in the guide."""
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", field_name)   # camelCase -> camel Case
    words = words.replace("_", " ")
    return words.strip().title()


def get_label(collection: str, field: str) -> Dict[str, str]:
    meta = LABEL_MAP.get(collection, {}).get(field)
    if meta is None:
        meta = GLOBAL_LABELS.get(field)
    if meta:
        return {
            "title": meta.get("title", humanize(field)),
            "description": meta.get("description", ""),
            "unit": meta.get("unit", ""),
            "domain": meta.get("domain", ""),
            "is_labelled": True,
        }
    return {
        "title": humanize(field),
        "description": "No description available yet -- add this field to LABEL_MAP / the guide.",
        "unit": "",
        "domain": "",
        "is_labelled": False,
    }


def serialize_value(value: Any) -> str:
    """Turn any BSON/Python value into a CSV-safe string."""
    if value is None:
        return ""
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, (dict, list)):
        try:
            return json.dumps(value, default=str, ensure_ascii=False)
        except TypeError:
            return str(value)
    return str(value)


def flatten_document(doc: Dict[str, Any]) -> Dict[str, Any]:
    """MongoDB documents are usually already flat enough; nested dicts/lists
    are kept intact and JSON-serialized as a single field value rather than
    exploded into many columns, so each row still maps to one labelled field."""
    return doc


